'use strict';
const assert=require('assert/strict'),{scopeHistory,retainMissingHistory}=require('../lib/sync_history_policy');
const prev={records:[{uid:'older',group:'older'},{uid:'current',group:'current'},{uid:'missing',group:'missing'}]};
const next={records:[{group:'older',businessDate:'2024-01-01'},{group:'current',businessDate:'2026-10-01'}]};
const scoped=scopeHistory(prev,next,'2026-09-22','2026-10-20');
assert.deepEqual(scoped.previous.records.map(r=>r.uid),['current','missing']);
assert.equal(scoped.current.records.length,1);
const p={ok:false,operations:{po:[]},conflicts:[{reason:'ambiguous_edit_key_change_or_deletion',group:'missing'},{reason:'ambiguous_edit_key_change_or_deletion',group:'current'}]};
const kept=retainMissingHistory('po',p,prev,next);
assert.equal(kept.retainedHistory.length,1);assert.equal(kept.conflicts.length,1);assert(!kept.ok);
assert.equal(prev.records.length,3);assert.equal(p.conflicts.length,2);
assert.throws(()=>scopeHistory(prev,next,'bad','2026-10-20'));
const {matchYarn}=require('../lib/yarn_sync_match');
const y={version:1,dispo:'nh/26/01',count:'20',lot:'0001',date:'2026-10-02',challan:'001',direction:'warp'};
const a={uid:'bound',group:'full-key',digest:'old',yarnIdentity:y};
const blank={...a,uid:'current-source',digest:'blank',yarnIdentity:{...y,direction:''}};
assert.equal(matchYarn({records:[a]},{records:[blank]}).pairs.length,1);
assert.equal(matchYarn({records:[blank]},{records:[{...a,digest:'later-number'}]}).pairs.length,1);
assert(matchYarn({records:[a,{...a,uid:'weft',digest:'weft',yarnIdentity:{...y,direction:'weft'}}]},{records:[blank]}).conflicts.length);
console.log('History retention and date-window tests passed');
